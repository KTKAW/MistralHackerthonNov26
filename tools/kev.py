#!/usr/bin/env python3
"""Refresh advisories/kev-recent.md from CISA's Known Exploited Vulnerabilities feed. Standard library only.

Usage:
  python3 tools/kev.py                 entries added in the last 14 days
  python3 tools/kev.py --days 30       a wider window
  python3 tools/kev.py --file kev.json read a saved copy of the feed instead of fetching it

The page is a snapshot: for offline use, and for reading next to the playbooks. An agent that can
reach the network should query the feed itself (see feeds.md). Run tools/lint.py --sync afterwards.
"""
from __future__ import annotations

import argparse
import collections
import datetime as dt
import json
import sys
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FEED = "https://www.cisa.gov/sites/default/files/feeds/known_exploited_vulnerabilities.json"
OUT = ROOT / "advisories" / "kev-recent.md"


def clean(value: object) -> str:
    """Feed text is data. Collapse whitespace and drop square brackets so it cannot form markdown links."""
    return " ".join(str(value).replace("[", "(").replace("]", ")").split())


def note_parts(entry: dict) -> list[str]:
    return [clean(part) for part in str(entry.get("notes", "")).split(" ; ") if part.strip()]


def load(path: str | None) -> dict:
    if path:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    request = urllib.request.Request(FEED, headers={"User-Agent": "kb-kev-snapshot"})
    with urllib.request.urlopen(request, timeout=60) as response:
        return json.load(response)


def render(feed: dict, days: int, today: dt.date) -> str:
    recent = [v for v in feed["vulnerabilities"] if (today - dt.date.fromisoformat(v["dateAdded"])).days <= days]
    recent.sort(key=lambda v: (v["dateAdded"], v["cveID"]), reverse=True)
    actions = collections.Counter(clean(v.get("requiredAction", "")) for v in recent)
    standard = actions.most_common(1)[0][0] if actions else ""
    ransomware = sum(1 for v in recent if v.get("knownRansomwareCampaignUse") == "Known")
    link_counts = collections.Counter(part for v in recent for part in note_parts(v))
    shared_links = [part for part, count in link_counts.items() if len(recent) > 1 and count > len(recent) / 2]

    lines = [
        "---",
        "type: feed-snapshot",
        f'title: "CISA KEV: entries added in the last {days} days"',
        f"feed: {FEED}",
        f"catalog_version: {clean(feed.get('catalogVersion', ''))}",
        f"fetched: {today.isoformat()}",
        f"window_days: {days}",
        f"entries: {len(recent)}",
        "generated: true",
        "---",
        "",
        f"# CISA KEV: entries added in the last {days} days",
        "",
        f"Generated by `python3 tools/kev.py` on {today.isoformat()} from catalog version {clean(feed.get('catalogVersion', ''))}, "
        f"which holds {feed.get('count', len(feed['vulnerabilities']))} entries in all. Do not edit by hand.",
        "",
        "Every entry is a vulnerability that CISA has evidence is being exploited. This page is a snapshot. "
        "For a live answer, query the feed: see [Feeds](../feeds.md). When an entry matches something you run, follow "
        "[An exploited vulnerability touches your stack](../playbooks/exploited-vulnerability.md).",
        "",
        "The entry text is CISA's, copied as data. Due dates bind US federal agencies only; read them as a measure of urgency.",
        "",
        f"**In this window:** {len(recent)} entries, {ransomware} with known use in ransomware campaigns.",
        "",
    ]
    if standard:
        lines += ["**Standard required action** (applies to every entry unless it states its own):", "", f"> {standard}", ""]
    if shared_links:
        lines += ["**Links that apply to most entries:** " + " ; ".join(shared_links), ""]
    lines += ["## Entries", ""]
    for v in recent:
        lines.append(f"### {clean(v['cveID'])} — {clean(v.get('vendorProject', ''))} {clean(v.get('product', ''))}")
        lines.append("")
        lines.append(f"- **Vulnerability:** {clean(v.get('vulnerabilityName', ''))}")
        lines.append(
            f"- **Added:** {clean(v['dateAdded'])} · **Due:** {clean(v.get('dueDate', ''))} · "
            f"**Ransomware use:** {clean(v.get('knownRansomwareCampaignUse', 'Unknown'))} · "
            f"**Forensic triage asked:** {clean(v.get('forensicTriage', 'not stated'))} · "
            f"**CWE:** {', '.join(clean(c) for c in v.get('cwes', [])) or 'not stated'}"
        )
        lines.append(f"- **What it is:** {clean(v.get('shortDescription', ''))}")
        action = clean(v.get("requiredAction", ""))
        if action and action != standard:
            lines.append(f"- **Required action:** {action}")
        own_links = [part for part in note_parts(v) if part not in shared_links]
        if own_links:
            lines.append(f"- **Links:** {' ; '.join(own_links)}")
        lines.append("")
    return "\n".join(lines).rstrip("\n") + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description="Write a snapshot of recent CISA KEV entries.")
    parser.add_argument("--days", type=int, default=14, help="how far back to look, by the date an entry was added (default 14)")
    parser.add_argument("--file", help="read the feed from a saved JSON file instead of fetching it")
    args = parser.parse_args()
    try:
        feed = load(args.file)
    except (OSError, ValueError) as error:
        print(f"could not read the feed: {error}", file=sys.stderr)
        return 1
    OUT.write_text(render(feed, args.days, dt.date.today()), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
